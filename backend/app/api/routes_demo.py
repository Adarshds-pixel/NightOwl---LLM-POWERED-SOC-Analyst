"""POST /demo/reset -- wipes ingested demo data so a fresh run (either the
one-shot "Run demo" pipeline or a manual EVTX upload) starts from a clean
slate instead of piling more events/alerts/incidents onto whatever is
already there.

GET /demo/fixtures and GET /demo/fixtures/{filename} -- serve the real-world
fixture pool Demo Mode ingests, so the *only* files it can ever pick from
are the same ones this project's own detection accuracy is measured
against (backend/scripts/build_failure_matrix.py), and only the ones the
*current* rule set actually detects -- reusing failure_matrix.json's real
`detected`/`behavior_hint`/`mitre_technique_ids` fields rather than a second,
hand-maintained fixture list that could drift from the real ground truth.
The frontend still fetches the file bytes and re-uploads them through the
real POST /ingest, same as any manual upload -- these two routes exist so
that upload has something real to fetch from without duplicating dozens of
EVTX files into the frontend's own static bundle.

Gated behind `require_demo_mode` in addition to the usual `require_api_key`
-- this is destructive (reset) or exposes internal fixture paths (fixtures),
and a deployment that is not meant to demo itself
(settings.demo_mode_enabled=False) should not expose any of it, not merely
rely on the shared API key being set.
"""

import json
from pathlib import Path

from fastapi import APIRouter, Depends, HTTPException
from fastapi.responses import FileResponse
from pydantic import BaseModel
from sqlalchemy.orm import Session

from app.core.config import settings
from app.db.session import get_db
from app.rag import cache as response_cache
from app.services import audit_service, demo_service

router = APIRouter()

_BACKEND_ROOT = Path(__file__).resolve().parents[2]
DETECTED_FIXTURES_DIR = _BACKEND_ROOT / "sample_logs" / "real_world_fixtures" / "detected"
FAILURE_MATRIX_PATH = _BACKEND_ROOT / "scripts" / "failure_matrix.json"


def require_demo_mode() -> None:
    if not settings.demo_mode_enabled:
        raise HTTPException(status_code=403, detail="demo mode is disabled on this deployment")


class DemoResetResponse(BaseModel):
    deleted: dict[str, int]


@router.post("/demo/reset", response_model=DemoResetResponse)
def reset_demo(db: Session = Depends(get_db)) -> DemoResetResponse:
    deleted = demo_service.reset_demo_data(db)
    # Ids restart at 1 after a reset; cached explanations for the previous
    # run's incident #1 must not be served for the new one.
    response_cache.clear()
    # Recorded after the delete commits, not before -- audit_log is one of
    # the tables being wiped, so a pre-reset entry would just be erased by
    # its own reset.
    audit_service.record_event(db, entity_type="demo", entity_id=0, action="reset", details=deleted)

    return DemoResetResponse(deleted=deleted)


class DemoFixtureInfo(BaseModel):
    filename: str
    label: str
    technique_ids: list[str]


class DemoFixturesResponse(BaseModel):
    fixtures: list[DemoFixtureInfo]


DEMO_MAX_FIXTURE_BYTES = 2 * 1024 * 1024


@router.get("/demo/fixtures", response_model=DemoFixturesResponse)
def list_demo_fixtures() -> DemoFixturesResponse:
    """Every real-world fixture the *current* rule set detects WITH THE CORRECT
    ATT&CK TECHNIQUE (failure_matrix.json's `correct_technique`), per the last
    `build_failure_matrix.py` run -- undetected fixtures are deliberately
    never listed here (they exist for detection-gap tracking, not for
    Demo Mode, which should never show "no detection" as the outcome of a
    click). `behavior_hint` is a real, human-written description of what
    each capture actually contains (see build_failure_matrix.py's own
    FixtureRecord), reused here as the demo label instead of inventing a
    second one.
    """
    if not FAILURE_MATRIX_PATH.exists():
        raise HTTPException(
            status_code=503,
            detail="Demo fixture catalog unavailable -- run backend/scripts/build_failure_matrix.py",
        )
    matrix = json.loads(FAILURE_MATRIX_PATH.read_text(encoding="utf-8"))
    fixtures = [
        DemoFixtureInfo(
            filename=entry["name"],
            label=entry.get("behavior_hint") or entry["name"],
            technique_ids=entry.get("mitre_technique_ids") or [],
        )
        for entry in matrix
        # Only list a fixture if it's both detected AND actually present on
        # disk -- the matrix and the directory are two separate artifacts
        # (one regenerated by a script, one populated by git), and this
        # route should never advertise a file it can't then serve.
        if entry.get("correct_technique", entry.get("detected"))
        and (DETECTED_FIXTURES_DIR / entry["name"]).is_file()
        # A demo click must finish in seconds: python-evtx parses about 100
        # records per second, so a multi-megabyte capture (the 10 MB PetitPotam
        # trace takes minutes) would hang the walkthrough. It stays a detected
        # fixture for the benchmark and for manual upload, just not a demo pick.
        and (DETECTED_FIXTURES_DIR / entry["name"]).stat().st_size <= DEMO_MAX_FIXTURE_BYTES
    ]
    return DemoFixturesResponse(fixtures=fixtures)


@router.get("/demo/fixtures/{filename}")
def get_demo_fixture(filename: str) -> FileResponse:
    """Streams one real fixture's raw bytes so the frontend can wrap it in a
    real File and POST it to /ingest, exactly like a manual upload.

    `filename` is checked against `Path(filename).name` (rejects any `/`,
    `\\`, or `..` segment) before being joined onto DETECTED_FIXTURES_DIR --
    this is the one place in the app that turns a client-supplied string
    directly into a filesystem path, so path traversal is the one thing
    this check exists to rule out.
    """
    safe_name = Path(filename).name
    if safe_name != filename:
        raise HTTPException(status_code=400, detail="Invalid fixture filename")
    path = DETECTED_FIXTURES_DIR / safe_name
    if not path.is_file():
        raise HTTPException(status_code=404, detail="Fixture not found")
    return FileResponse(path, media_type="application/octet-stream", filename=safe_name)
