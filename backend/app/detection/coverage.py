# Event types ingest reports as an informational notice instead of an alert.
# System 104 ("an event log was cleared") used to be a high-severity detection
# and turned a benign server -- whose administrator really did clear its logs --
# into "Suspicious". It is now shown as a notice naming the account and log; the
# Security-log equivalent (1102), the one attackers use, remains a detection.
NOTICE_PAIRS: frozenset[tuple[str | None, int]] = frozenset({("system", 104)})


def checked_pairs(rules: list[LoadedRule]) -> frozenset[tuple[str | None, int]]:
    """(channel token, event id) pairs a loaded rule, a sequence detector or the
    notice generator evaluates."""
    return covered_event_ids(rules) | SEQUENCE_INPUTS | NOTICE_PAIRS


def routine_reason(token: str | None, event_id: int) -> str | None:
    """Why this event type is everyday noise, or None if it is not routine."""
    if (token, event_id) in NEVER_ROUTINE:
        return None
    if token in ROUTINE_EVENTS and event_id in ROUTINE_EVENTS[token]:
        return ROUTINE_EVENTS[token][event_id]
    if token in DEFAULT_ROUTINE_CHANNELS:
        return "Operational event from the " + token + " log"
    return None


def classify(token: str | None, event_id: int, checked: frozenset[tuple[str | None, int]]) -> str:
    if (token, event_id) in checked:
        return CHECKED
    if routine_reason(token, event_id) is not None:
        return ROUTINE
    return UNCHECKED
