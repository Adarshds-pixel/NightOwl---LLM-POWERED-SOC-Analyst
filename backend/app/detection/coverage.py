"""Which events NightOwl actually judges, and which are everyday noise.

Every event type (channel + event id) in an upload falls into one of three kinds:

* CHECKED   -- a loaded Sigma rule or a sequence detector evaluates it.
* ROUTINE   -- everyday operating-system activity that no attack rule needs to
               look at: credential-manager reads, process exits, logoffs,
               service status changes. A file made of these is normal.
* UNCHECKED -- security-relevant (or unknown) activity that nothing evaluates.
               Only these make a file "worth a review".

Before this module, ROUTINE did not exist: any event type without a rule counted
as "no coverage", so almost every real benign file read "Inconclusive". The
routine lists below were built from the measured benign corpus (31 real captures
from two machines plus the real-world benign set): each entry is an event type
that appears constantly on healthy machines and carries no attack signal on its
own. The attack signal in these channels lives in other events (process start,
logon, service install) that rules do evaluate.
"""

from __future__ import annotations

from app.detection.engine import covered_event_ids
from app.detection.rule_loader import LoadedRule
from app.detection.sequences import SEQUENCE_INPUTS

CHECKED = "checked"
ROUTINE = "routine"
UNCHECKED = "unchecked"

# Channels whose events are operational by nature. (BITS is deliberately NOT here:
# it is a classic command-and-control and download channel -- T1197 -- and the
# whole channel being "everyday" made a malicious BITS capture read Normal. Only
# its job-lifecycle results are listed as routine below; job creation, which
# names the owning process, is judged by a rule.) System and Application hold
# hundreds of event ids per machine (power, drivers, updates, app crashes);
# the attack-relevant ones (7045 service install, 104 log cleared, MSI installs
# from a URL) are covered by rules and therefore CHECKED before this applies.
DEFAULT_ROUTINE_CHANNELS = frozenset({"system", "application"})

# Never routine, whatever the channel default says: these are attack signals in
# an otherwise operational log. Rules cover them today; if a rule is ever
# removed they must show up as unchecked, not vanish into "everyday".
NEVER_ROUTINE = frozenset({("system", 7045), ("system", 104)})

